import { createAdminClient } from "@/lib/supabase/admin";

/**
 * Sending the notifications the queue holds, through Expo.
 *
 * WHY EXPO AND NOT APPLE AND GOOGLE DIRECTLY. The app is built with EAS, so every installation already has an
 * Expo push token, and Expo's service holds the APNs key and the FCM credentials on its side. Talking to APNs
 * and FCM ourselves would mean two protocols, two credential rotations and a certificate that expires in a
 * year on a server nobody is watching. The trade is that a notification passes through one more party; it
 * carries a title, a sentence and an id — never an amount, never a name — which is the same rule the SMS
 * bodies follow.
 *
 * ONE QUEUE, TWO DISPATCHERS. The rows live in public.notification_outbox beside the text messages, so «what
 * was this client told» has one answer. 0139 split the claim by channel after the fault was found: before it,
 * public.claim_notifications took the oldest due row whatever its channel and src/lib/sms.ts would have sent
 * a push out as a text message.
 */

/**
 * The three functions 0138 and 0139 added, typed by hand.
 *
 * src/lib/supabase/database.types.ts is generated by `npm run db:types`, which reads the Management API —
 * and the project's SUPABASE_ACCESS_TOKEN has expired, so that command answers 401. Hand-editing the
 * generated file would be worse than this: the next successful generation reverts it silently, and nobody
 * would know the types had ever disagreed with the schema. So the three calls go through one narrow door,
 * named after the migration that created them. The day the token is renewed, `npm run db:types` carries
 * them properly and this type can go.
 */
type PushRow = {
  id: string;
  to_phone_e164: string;
  body: string;
  template_key: string | null;
};
type Delivery = { token: string; title: string; body: string };

function pushClient(extraHeaders: Record<string, string> = {}) {
  return createAdminClient(extraHeaders) as unknown as {
    rpc: {
      (fn: "register_push_token", args: { p_token: string; p_platform: string; p_phone?: string | null; p_app_version?: string | null }): PromiseLike<{ data: { ok: boolean; linked: boolean } | null; error: { message: string } | null }>;
      (fn: "disable_push_token", args: { p_token: string; p_reason?: string }): PromiseLike<{ error: { message: string } | null }>;
      (fn: "claim_push_notifications", args: { p_limit?: number }): PromiseLike<{ data: PushRow[] | null; error: { message: string } | null }>;
      (fn: "push_delivery", args: { p_id: string }): PromiseLike<{ data: Delivery[] | null; error: { message: string } | null }>;
      (fn: "mark_notification_sent", args: { p_id: string; p_provider: string; p_provider_message_id?: string }): PromiseLike<{ error: { message: string } | null }>;
      (fn: "mark_notification_failed", args: { p_id: string; p_error: string; p_provider: string }): PromiseLike<{ error: { message: string } | null }>;
      (fn: "release_stuck_notifications", args?: Record<string, never>): PromiseLike<{ error: { message: string } | null }>;
    };
  };
}

export type RegisterOutcome = { ok: true; linked: boolean } | { ok: false; reason: "invalid_token" | "invalid_platform" | "failed"; message: string };

/** Stores one installation's token. The reasons are the exceptions 0138 raises, mapped to what the app shows. */
export async function registerPushToken(
  input: { token: string; platform: "ios" | "android"; phone?: string | null; appVersion?: string | null },
  extraHeaders: Record<string, string> = {},
): Promise<RegisterOutcome> {
  const { data, error } = await pushClient(extraHeaders).rpc("register_push_token", {
    p_token: input.token,
    p_platform: input.platform,
    p_phone: input.phone ?? null,
    p_app_version: input.appVersion ?? null,
  });

  if (error) {
    const message = error.message ?? "";
    if (message.includes("push_token_invalid")) return { ok: false, reason: "invalid_token", message };
    if (message.includes("push_platform_invalid")) return { ok: false, reason: "invalid_platform", message };
    return { ok: false, reason: "failed", message };
  }
  return { ok: true, linked: Boolean(data?.linked) };
}

export type PushOutcome = { claimed: number; sent: number; failed: number; retired: number; blocked?: string };

/** Expo's answer for one message. `DeviceNotRegistered` is the only one that means «stop trying this token». */
type Ticket = { status: "ok"; id?: string } | { status: "error"; message?: string; details?: { error?: string } };

const EXPO_ENDPOINT = "https://exp.host/--/api/v2/push/send";
/** Expo accepts a hundred messages in one request; a queue batch is 50 by default, so this is rarely two. */
const CHUNK = 100;

/**
 * Drains the push side of the queue.
 *
 * A ROW IS A PERSON, A SEND IS A DEVICE. One queued notification fans out to every device that phone has
 * registered, and the row is sent only if at least one device accepted it. A row whose devices have all
 * been uninstalled in the meantime is marked failed with that reason rather than silently dropped — the
 * client was not told, and the history has to say so.
 *
 * It never throws. A dispatcher that throws takes down whatever called it — a form submission, a cron hit —
 * and the queue is designed so that the next run retries anyway.
 */
export async function dispatchPush(limit?: number): Promise<PushOutcome> {
  const supabase = pushClient();

  // A run that died leaves rows marked sending; they go back before this one claims. Shared with the SMS
  // dispatcher on purpose: one definition of «stuck».
  await supabase.rpc("release_stuck_notifications");

  const { data: claimed, error } = await supabase.rpc("claim_push_notifications", { p_limit: limit });
  if (error) return { claimed: 0, sent: 0, failed: 0, retired: 0, blocked: `تعذّر قراءة الصف: ${error.message}` };

  const batch = claimed ?? [];
  if (batch.length === 0) return { claimed: 0, sent: 0, failed: 0, retired: 0 };

  let sent = 0;
  let failed = 0;
  let retired = 0;

  for (const row of batch) {
    const { data: devices } = await supabase.rpc("push_delivery", { p_id: row.id });
    const targets = devices ?? [];

    if (targets.length === 0) {
      await supabase.rpc("mark_notification_failed", {
        p_id: row.id,
        p_error: "لا يوجد جهاز مسجّل على هذا الرقم.",
        p_provider: "expo",
      });
      failed += 1;
      continue;
    }

    let accepted = 0;
    let lastError = "";

    for (let i = 0; i < targets.length; i += CHUNK) {
      const chunk = targets.slice(i, i + CHUNK);
      const controller = new AbortController();
      const timer = setTimeout(() => controller.abort(), 15_000);
      let tickets: Ticket[] = [];

      try {
        const response = await fetch(EXPO_ENDPOINT, {
          method: "POST",
          headers: { "content-type": "application/json", accept: "application/json" },
          body: JSON.stringify(
            chunk.map((device) => ({
              to: device.token,
              title: device.title,
              body: device.body,
              sound: "default",
              // High so a reminder about money arrives when it is sent rather than in the next maintenance
              // window the phone decides on.
              priority: "high",
              // What the app opens on when the notification is tapped. Ids only; nothing readable.
              data: { outboxId: row.id, template: row.template_key },
            })),
          ),
          signal: controller.signal,
        });

        if (!response.ok) {
          lastError = `Expo answered ${response.status}`;
          continue;
        }
        const json = (await response.json()) as { data?: Ticket[] };
        tickets = json.data ?? [];
      } catch (cause) {
        lastError = cause instanceof Error ? cause.message : "تعذّر الاتصال بخدمة الإشعارات.";
        continue;
      } finally {
        clearTimeout(timer);
      }

      for (const [index, ticket] of tickets.entries()) {
        const device = chunk[index];
        if (!device) continue;
        if (ticket.status === "ok") {
          accepted += 1;
          continue;
        }
        lastError = ticket.message ?? ticket.details?.error ?? "رفضت خدمة الإشعارات الرسالة.";
        // The app was uninstalled or the token rotated. Retrying it every few minutes forever helps nobody.
        if (ticket.details?.error === "DeviceNotRegistered") {
          await supabase.rpc("disable_push_token", { p_token: device.token, p_reason: "DeviceNotRegistered" });
          retired += 1;
        }
      }
    }

    if (accepted > 0) {
      await supabase.rpc("mark_notification_sent", { p_id: row.id, p_provider: "expo" });
      sent += 1;
    } else {
      await supabase.rpc("mark_notification_failed", {
        p_id: row.id,
        p_error: lastError || "لم يقبل أي جهاز الإشعار.",
        p_provider: "expo",
      });
      failed += 1;
    }
  }

  return { claimed: batch.length, sent, failed, retired };
}
